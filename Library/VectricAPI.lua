-- MaterialBlock
--
-- This object represents the material block within the program. It holds the width, height and
-- thickness of the job and also the XY and Z origins. There is a single instance of the material block in
-- the program. A number of methods are provided to covert between 'absolute' z values and z values
-- relative to the surface of the material. These are very useful what writing scripts for toolpath
-- generation as scripts need to take account of the fact that the user may change between Z0 on the
-- machine representing the bottom of the material or the top of the material.
--------------------------------------------------------------------------------

---@alias ZOrigin integer
---@alias FlipDirection integer
---@alias JobType integer
---@alias RotationAxis integer

---@class MaterialBlock
---@field ActualXYOrigin Point2D XY position for user specified origin position on material (see .XYOrigin). R/O.
---@field BlcOrigin Point3D XYZ position for bottom left corner of material block. R/O.
---@field Height number height of material - length in Y. R/O.
---@field InMM boolean true if the job / job is in MM else it is in inches. R/O.
---@field MaterialBox Box3D the 3D bounding box for the material. R/O.
---@field MaterialSurfaceZ number Z value for surface of material. R/O.
---@field Thickness number thickness of material - length in Z. R/O.
---@field Width number width of material - length in X. R/O.
---@field CylinderDiameter number (Rotary Only) the diameter of the material cylinder. R/O.
---@field CylinderLength number (Rotary Only) the length of the material cylinder. R/O.
---@field XYOrigin MaterialBlock.XYOrigin Value indicating position in material chosen as XY origin. R/O.
---@field ZOrigin ZOrigin Value indicating position of Z origin. R/O.
---@field FlipDirection FlipDirection (Double-Sided Only) Values indicating how we flip the material in a two sided job. R/W.
---@field JobType JobType Values indicating the value of the current job. R/W.
---@field RotationAxis RotationAxis (Rotary Only) Values indicating the rotation axis of the cylinder. R/O.
---@field BLC MaterialBlock.XYOrigin Bottom Left Corner of material.
---@field BRC MaterialBlock.XYOrigin Bottom Right Corner of material.
---@field TRC MaterialBlock.XYOrigin Top Right Corner of material.
---@field TLC MaterialBlock.XYOrigin Top Left Corner of material.
---@field CENTRE MaterialBlock.XYOrigin Centre of material (Note British spelling!).
---@field Z_TOP ZOrigin Top of material.
---@field Z_CENTRE ZOrigin Centre of material (Note British spelling!).
---@field Z_BOTTOM ZOrigin Bottom of material.
---@field SINGLE_SIDED JobType Single sided job.
---@field DOUBLE_SIDED JobType Double sided job.
---@field ROTARY JobType Rotary job.
---@field X_AXIS RotationAxis Rotation axis of the cylinder is X.
---@field Y_AXIS RotationAxis Rotation axis of the cylinder is Y.
---@overload fun(): MaterialBlock
MaterialBlock = {}

