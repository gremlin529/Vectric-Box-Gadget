-- VectricJob
--
-- This is the main object a script writer will interact with and represents the currently open job (file)
-- within the application. There are members of the object which will tell you if there is an existing job
-- open and also to allow you to create a new job.
--------------------------------------------------------------------------------

---@class VectricJob
---@field Exists boolean returns true if there is an existing job open. R/O.
---@field DocumentVariables DocumentVariableList returns the DocumentVariableList for the job. The variable list allows for user defined values to be used in formulas. R/O.
---@field Height number returns height of the job along y - same as YLength. R/O.
---@field IsAspire boolean returns true if the script is running inside Aspire. R/O.
---@field IsBetaBuild boolean returns true if this is a Beta build rather than a release build. R/O.
---@field InInches boolean returns true if the current units are inches. R/O.
---@field InMM boolean returns true if the current units are mm. R/O.
---@field JobParameters utParameterList returns the utParameterList for the job (documented as ".Job Parameters"). The parameter list allows scripts to store persistent data with the job. R/O.
---@field LayerManager CadLayerManager for the job. This manages all the layers which in turn hold all the vector objects in the job. R/O.
---@field MinX number returns X coordinate of bottom left corner of job. R/O.
---@field MinY number returns Y coordinate of bottom left corner of job. R/O.
---@field Name string returns the name of the current job WITHOUT the file extension e.g. "test" not "test.crv". R/O.
---@field PostProcessorParameters utParameterList returns the utParameterList for the last run of a post processor. This will hold information such as the PostP used, the tools used and the actual toolpath files output. R/O.
---@field Selection SelectionList returns the SelectionList for the currently selected vectors in the job. R/O.
---@field SheetManager CadSheetManager for the job. This manages all the sheets in the job. R/O.
---@field Width number returns width of the job along x - same as XLength. R/O.
---@field XLength number returns length of the job along x - same as XLength. R/O.
---@field YLength number returns length of the job along Y - same as Height. R/O.
---@field AROUND_X integer Flip around the X axis.
---@field AROUND_Y integer Flip around the Y axis.
