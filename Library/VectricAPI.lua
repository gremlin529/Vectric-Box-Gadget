---------------------------------------------------------------------------
-- Toolpaths
--
-- The objects in this section allow the script writer to create toolpaths
-- within the program. There are two types of toolpaths which can be
-- created from scripts:
--   1) Standard Vectric toolpaths - the same toolpaths you would have
--      created within the program using the Profile, Pocketing, VCarving
--      etc. forms. From script you can fill out all the same parameters
--      that you would manually in the program, and the user can edit the
--      toolpaths within the interface to change parameters and
--      recalculate. These toolpaths are created for the currently
--      selected vectors (the selection can also be controlled from
--      script).
--   2) External toolpaths - toolpaths which are created entirely from
--      within the script. The script creates contours which represent the
--      movement of the tool. As these toolpaths are not related to the
--      geometry in the main program, the user can not recalculate them,
--      but would need to delete them and re-run the script to recreate a
--      new version.
---------------------------------------------------------------------------

