---This object is the base class for all the different types of components managed by the
---ComponentManager. There are two classes of Component available to Lua; Component itself and
---ComponentGroup. Components reference the Reliefs that were used to create them. It is possible to
---have multiple Components referring to the same original Relief and this should be kept in mind while
---manipulating Component data. Aspire only.
---@class Component
---@field Id UUID R/O. Returns the id of the component. Aspire only.
---@field CombineMode CombineMode R/W. The combine mode of the component. Aspire only.
---@field IsTilted boolean R/O. Returns true if the component is tilted. Aspire only.
---@field UseTilt boolean R/W. Is the component using tilt. Aspire only.
---@field IsFaded boolean R/O. Returns true if the component is faded. Aspire only.
---@field UseFade boolean R/W. Is the component using fade. Aspire only.
